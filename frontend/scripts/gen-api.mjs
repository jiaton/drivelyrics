// Generates src/lib/api-types.ts from src/lib/openapi.json (written by the backend's
// scripts/export_openapi.py). `npm run gen:api` writes it; src/lib/api-types.test.ts
// fails while the committed file is stale, so a schema change can't drift silently.
import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const HEADER = "// Generated by `npm run gen:api` from src/lib/openapi.json — do not edit.\n\n";
const SPEC = new URL("../src/lib/openapi.json", import.meta.url);
const OUT = new URL("../src/lib/api-types.ts", import.meta.url);

export async function generate() {
  const spec = JSON.parse(await readFile(SPEC, "utf8"));
  return HEADER + astToString(await openapiTS(spec));
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  await writeFile(OUT, await generate());
  console.log(`wrote ${OUT.pathname}`);
}
